package com.irisgame.model;

public class MakeupSelection {
    private String modelId;
    private String foundation;
    private String hairStyle;
    private String hairColor;
    private String blush;
    private String eyeshadow;
    private String lipstick;
    private String accessory;
    private String eyelashes;
    private String lipFinish;
    private String pose;
    private String expression;
    private String gadget;

    public MakeupSelection() {}

    public String getModelId() { return modelId; }
    public void setModelId(String modelId) { this.modelId = modelId; }

    public String getFoundation() { return foundation; }
    public void setFoundation(String foundation) { this.foundation = foundation; }

    public String getHairStyle() { return hairStyle; }
    public void setHairStyle(String hairStyle) { this.hairStyle = hairStyle; }

    public String getHairColor() { return hairColor; }
    public void setHairColor(String hairColor) { this.hairColor = hairColor; }

    public String getBlush() { return blush; }
    public void setBlush(String blush) { this.blush = blush; }

    public String getEyeshadow() { return eyeshadow; }
    public void setEyeshadow(String eyeshadow) { this.eyeshadow = eyeshadow; }

    public String getLipstick() { return lipstick; }
    public void setLipstick(String lipstick) { this.lipstick = lipstick; }

    public String getAccessory() { return accessory; }
    public void setAccessory(String accessory) { this.accessory = accessory; }

    public String getEyelashes() { return eyelashes; }
    public void setEyelashes(String eyelashes) { this.eyelashes = eyelashes; }

    public String getLipFinish() { return lipFinish; }
    public void setLipFinish(String lipFinish) { this.lipFinish = lipFinish; }

    public String getPose() { return pose; }
    public void setPose(String pose) { this.pose = pose; }

    public String getExpression() { return expression; }
    public void setExpression(String expression) { this.expression = expression; }

    public String getGadget() { return gadget; }
    public void setGadget(String gadget) { this.gadget = gadget; }
}
